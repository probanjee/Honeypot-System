const User = require('../models/User.model');
const { hashPassword, comparePassword } = require('../utils/hash');
const { generateJWT } = require('../utils/jwt');

const supabase = require('../config/supabase');

const login = async (email, password) => {
    if (process.env.USE_SUPABASE === 'true') {
        const { data, error } = await supabase.auth.signInWithPassword({ email, password });
        if (error) {
            console.error('[Supabase Auth Error]', error.message);
            return null;
        }
        return data; // Returns { user, session }
    }

    const user = await User.findOne({ email });
    if (!user || !user.passwordHash) return null;
    
    const isMatch = await comparePassword(password, user.passwordHash);
    if (!isMatch) return null;
    
    return user;
};

const generateToken = (userOrSession) => {
    if (process.env.USE_SUPABASE === 'true') {
        // If Supabase is active, the auth.service.login returned { user, session }
        // The token is already generated by Supabase (access_token)
        return userOrSession.session ? userOrSession.session.access_token : null;
    }

    // Legacy manual JWT generation
    return generateJWT({ id: userOrSession._id, role: userOrSession.role, email: userOrSession.email });
};

module.exports = { login, generateToken };
